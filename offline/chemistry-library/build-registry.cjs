'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const root = __dirname;
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const manifest = read('manifest.json');
assert.equal(manifest.schemaVersion, 1, 'Unsupported built-in library manifest');

function loadSection(name, {file, files, order}) {
  if (file) return read(file);
  const records = new Map();
  for (const source of files) {
    for (const [id, record] of Object.entries(read(source))) {
      assert.ok(!records.has(id), name + ' has a duplicate key: ' + id);
      records.set(id, record);
    }
  }
  assert.equal(order.length, records.size, name + ' has an incomplete order list');
  assert.equal(new Set(order).size, order.length, name + ' has duplicate keys in its order list');
  return Object.fromEntries(order.map(id => {
    assert.ok(records.has(id), name + ' is missing ' + id);
    return [id, records.get(id)];
  }));
}

const registry = Object.fromEntries(Object.entries(manifest.sections).map(([name, section]) =>
  [name, loadSection(name, section)]));
const bundle = '// Generated by chemistry-library/build-registry.cjs from manifest.json.\n' +
  'const BUILTIN_CHEMISTRY_DATA = JSON.parse(' + JSON.stringify(JSON.stringify(registry)) + ');\n';
const output = path.join(root, 'registry.generated.js');
if (process.argv.includes('--check')) {
  assert.ok(fs.readFileSync(output, 'utf8') === bundle, 'Built-in bundle is stale. Run build-registry.cjs.');
} else {
  fs.writeFileSync(output, bundle);
}
