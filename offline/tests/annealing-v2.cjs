'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context=vm.createContext({console,crypto:require('node:crypto').webcrypto});
require('./load-registry.js')(context);
for(const file of ['snapshots/A/app/core','optical',
 'snapshots/A/app/chemistry','snapshots/A/app/reactions',
 'molecule-builder','annealing','structure-presentation'])
 vm.runInContext(fs.readFileSync(path.join(__dirname,'../app',file+'.js'),'utf8'),context,{filename:file});
const [Lite,Annealing,MoleculeBuilder,StructurePresentation]=vm.runInContext('[Lite,Annealing,MoleculeBuilder,StructurePresentation]',context);
const seq=(s,fn=()=> 'r')=>[...s].map((b,i)=>fn(i)+b).join('');
const view=s=>Annealing.resolve(Lite.calculate(s));
const aCore='AAGCUACGUGACUACGUGC';
const complement={A:'U',C:'G',G:'C',U:'A'};
const bCore=[...aCore].reverse().map(b=>complement[b]).join('');
const a=seq(aCore+'UU'),b=seq(bCore+'UU');
const av=view(a),bv=view(b);
const duplex=(x,y,design)=>Annealing.duplex(view(x),view(y),undefined,design);
const best=duplex(a,b);
assert.equal(best.feasibility,'Compatible');
assert.equal(best.pairs.length,19);
assert.deepEqual(JSON.parse(JSON.stringify(best.overhangs)),{a5:[],a3:[20,21],b5:[],b3:[20,21]});
const pairs=(result,reverse=false)=>Array.from(result.pairs,p=>reverse?p.b+':'+p.a:p.a+':'+p.b).sort();
assert.deepEqual(pairs(best),pairs(duplex(b,a),true));
const modified=seq(aCore+'UU',i=>i%2?'m':'f');
const ps=modified.slice(0,2)+'*'+modified.slice(2);
assert.equal(duplex(ps,b).feasibility,'Compatible');
assert.deepEqual(pairs(best),pairs(duplex(ps,b)));
const mutation=(s,i)=>s.slice(0,i)+({A:'C',C:'A',G:'A',U:'C'}[s[i]])+s.slice(i+1);
assert.equal(duplex(seq(mutation(aCore+'UU',9)),b).feasibility,'Partial');
assert.equal(duplex(seq(mutation(aCore+'UU',2)),b).feasibility,'Likely');
assert.equal(duplex(seq(mutation(aCore+'UU',0)),b).feasibility,'Likely');
const repeated=duplex(seq('A'.repeat(19)),seq('U'.repeat(18)));
assert(repeated.ambiguous);
assert.equal(repeated.feasibility,'Partial');
const spacer=a.slice(0,12)+'[absic]'+a.slice(14);
const interrupted=duplex(spacer,b);
assert.equal(interrupted.feasibility,'Partial');
assert(interrupted.columns.some(c=>c.kind==='abasic'));
Lite.registerCustom('UnknownInner',Lite.selectAttachments(Lite.parseSmiles('OCCO'),0,3));
const unresolved=duplex(a.slice(0,12)+'[UnknownInner]'+a.slice(14),b);
assert.equal(unresolved.feasibility,'Unresolved');
assert(unresolved.columns.some(c=>c.kind==='unknown'));
assert.equal(duplex(a+'[invAb]',b).feasibility,'Unresolved');
assert.equal(duplex(a.slice(0,14)+'rA'+a.slice(14),b).pairs.length<19,true);
const designed=duplex(a,b,{offset:best.offset,coreA:[1,19],coreB:[1,19],overhangs:{a3:[20,21],b3:[20,21]}});
assert.equal(designed.intendedCoreCoverage.a,1);
assert.equal(designed.intendedCoreCoverage.b,1);
const self=Annealing.self(view(seq('GCGCAAAAGCGC')));
assert(self.hairpins.some(c=>c.length===4&&c.gc===4&&c.strong&&c.loop.length===4));
assert(Annealing.self(view(seq('GCGCGCGC'))).dimers.some(c=>c.offset===0&&c.strong));
assert.equal(Annealing.self(view(seq('AAAACCCC'))).totals.dimers,0);
const xna=view('tAtCtGtAtC');
assert.equal(xna.topologyStatus,'resolved');
assert.equal(Annealing.duplex(xna,bv).feasibility,'Not assessed');
const state=MoleculeBuilder.start(ps);
const before=MoleculeBuilder.exportJSON(state);
const markup=StructurePresentation.duplex([Annealing.resolve(state),bv],duplex(ps,b));
assert(markup.includes('data-linkage="PS"'));
assert(markup.includes('data-analysis-layer="non-covalent"'));
assert(markup.includes('data-base='));
assert.equal(MoleculeBuilder.exportJSON(state),before);
console.log('Duplex / Self Analysis 2.0 acceptance passed');

